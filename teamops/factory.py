"""Agent Factory — template-only blueprint generator.

Catalog review #3: the plugin no longer shells out to a home-directory script
(``~/agentic-coding-team.sh --auto`` was a review blocker). The generator is
reviewable source inside the plugin: given a natural-language spec it either
extends a base blueprint with a new role or scaffolds a minimal team from the
roles named in the spec. A pre-baked fixture (``blueprints/fixtures/``) is
still available for demos via ``use_fixture`` — a deterministic, tested output
that never depends on external machinery.

All paths the generator reads/writes stay under the plugin's ``blueprints/``
dir (or an owner-configured root the caller resolves); nothing outside.
"""
from __future__ import annotations

import json
import re
import shutil
from pathlib import Path

BLUEPRINTS_DIR = Path(__file__).resolve().parent / "blueprints"
FIXTURES_DIR = BLUEPRINTS_DIR / "fixtures"

_DEFAULT_ROLE_TEMPLATE = """# SOUL — {role}

You are the {role} agent in the '{team}' team ({rid}).

## Role
{summary}

## Mesh edges
{edges}

## Working contract
- Read your INBOX drop file at the start of every shift.
- Act on items; write your outputs to the destination agent's INBOX per the
  MESH-MAP edge contract.
- Never invent data you cannot see; report blockers instead.
"""


def _slugify(text: str) -> str:
    s = text.lower().strip()
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")
    return s[:40].rstrip("-") or "generated"


def _parse_spec(spec: str) -> tuple[str | None, str | None]:
    """Parse a factory spec into (role_to_add, base_blueprint).

    Patterns:
      "add a billing agent to sales"          -> ("billing-agent", "sales")
      "extend the sales blueprint with a support lead" -> ("support-lead", "sales")
      None -> scaffold mode (role/base both None).
    """
    s = spec.strip().lower()
    m = re.search(r"add an?\s+([a-z][a-z0-9-]*(?:\s[a-z][a-z0-9-]*)?)\s+(?:agent|role)?\s*to\s+(?:the\s+)?([a-z0-9_-]+)", s)
    if not m:
        m = re.search(r"extend\s+(?:the\s+)?([a-z0-9_-]+)\s+blueprint\s+with\s+an?\s+([a-z][a-z0-9-]*(?:\s[a-z][a-z0-9-]*)?)", s)
        if m:
            return ("-".join(m.group(2).split()), m.group(1))
        return None, None
    role = "-".join(m.group(1).split())
    base = m.group(2)
    return role, base


def _roles_from_spec(spec: str, fallback: str) -> list[str]:
    """Scaffold mode: extract role names from tokens like 'dispatcher, field-agent, boss'."""
    roles: list[str] = []
    m = re.search(r":\s*([a-z0-9_,\s-]+)$", spec.strip())
    if m:
        parts = [p.strip() for p in m.group(1).split(",")]
        roles = ["-".join(p.split()) for p in parts if p and re.fullmatch(r"[a-z0-9-]+(?:\s[a-z0-9-]+)*", p)]
    roles = [r for r in roles if r]
    if not roles:
        roles = [fallback]
    return roles


def _edge_lines(edges: list[dict], role: str) -> str:
    lines = [f"- {e['from']} -> {e['to']} via {e.get('artifact', 'inbox-drop')}" for e in edges
             if role in (e.get("from"), e.get("to"))]
    return "\n".join(lines) if lines else "- none"


def _write_assets(target: Path, name: str, roles: list[dict], edges: list[dict]) -> None:
    """Write assets/{mesh,kanban}.json for a team; callers own team.yaml/souls/crons."""
    assets = target / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    shared_files = sorted({f"INBOX-{r['name']}.md" for r in roles})
    (assets / "mesh.json").write_text(json.dumps({
        "version": "0.1", "edges": edges, "shared_files": shared_files,
    }, indent=2))
    tasks = {}
    for i, role in enumerate(roles, start=1):
        tasks[f"seed_{i}"] = {
            "id": f"seed_{i}", "title": f"First {role['name']} shift: read INBOX-{role['name']}.md",
            "assignee": role["name"], "status": "TODO",
            "deliverables": "outputs per mesh edge contract",
            "notes": "Generated by Agent Factory; replace with real work at deploy.",
        }
    (assets / "kanban.json").write_text(json.dumps({
        "columns": ["TODO", "IN_PROGRESS", "REVIEW", "DONE"], "tasks": tasks,
    }, indent=2))


def _extend_blueprint(base_dir: Path, role: str, team_name: str,
                      summary: str, target_dir: Path) -> None:
    """Clone a base blueprint and append a new role (soul template, mesh, kanban)."""
    try:
        import yaml
    except ImportError as e:  # pragma: no cover
        raise RuntimeError("PyYAML required for factory extension") from e

    team = yaml.safe_load((base_dir / "team.yaml").read_text()) or {}
    if not team.get("roles"):
        raise ValueError(f"base blueprint {base_dir.name} has no roles to extend")
    roles = list(team["roles"])
    existing = {r.get("name") for r in roles}
    if role in existing:
        raise ValueError(f"role '{role}' already exists in base blueprint {base_dir.name}")
    roles.append({"name": role, "title": role.replace("-", " ").title(),
                  "soul": f"souls/{role}.md"})
    team["roles"] = roles
    team["name"] = team_name
    team.pop("version", None)

    # souls: copy existing, write the new role's from the template
    shutil.copytree(base_dir / "souls", target_dir / "souls", dirs_exist_ok=True)
    base_edges = []
    mesh_path = base_dir / "assets" / "mesh.json"
    if mesh_path.exists():
        try:
            base_edges = json.loads(mesh_path.read_text()).get("edges", [])
        except (json.JSONDecodeError, ValueError):
            base_edges = []
    hub = next((r["name"] for r in roles if r["name"] in ("boss", "owner", base_dir.name)), roles[0]["name"])
    edges = list(base_edges) + [
        {"from": hub, "to": role, "via": "inbox-drop", "artifact": f"INBOX-{role}.md"},
        {"from": role, "to": hub, "via": "inbox-drop", "artifact": f"INBOX-{hub}.md"},
    ]
    rid = f"R{len(roles)}"
    (target_dir / "souls" / f"{role}.md").write_text(
        _DEFAULT_ROLE_TEMPLATE.format(role=role, team=team_name, rid=rid,
                                      summary=summary or f"New {role} role added by the Agent Factory.",
                                      edges=_edge_lines(edges, role)))

    (target_dir / "team.yaml").write_text(_dump_yaml(team))
    # crons: keep base crons (paths stay relative), add a daily brief for the new role
    crons = []
    if (base_dir / "crons.yaml").exists():
        try:
            crons = list((yaml.safe_load((base_dir / "crons.yaml").read_text()) or {}).get("crons") or [])
        except Exception:  # noqa: BLE001
            crons = []
    crons.append({"name": f"{team_name}-{role}-morning-brief", "schedule": "0 9 * * *",
                  "profile": role,
                  "prompt": f"As {role}, run the daily brief: read your INBOX drop file and report status to the hub."})
    (target_dir / "crons.yaml").write_text(_dump_yaml({"crons": crons}))
    _write_assets(target_dir, team_name, roles, edges)


def _scaffold_team(spec: str, team_name: str, roles: list[str], target_dir: Path) -> None:
    """Build a minimal team blueprint from a role list (no base)."""
    role_dicts = []
    edges: list[dict] = []
    for i, role in enumerate(roles, start=1):
        role_dicts.append({"name": role, "title": role.replace("-", " ").title(),
                           "soul": f"souls/{role}.md"})
    for i in range(1, len(roles)):
        edges.append({"from": roles[i - 1], "to": roles[i], "via": "inbox-drop",
                      "artifact": f"INBOX-{roles[i]}.md"})
    team = {"name": team_name, "description": (f"Factory-scaffolded team from spec: {spec}")[:200],
            "roles": role_dicts,
            "shared": {"kanban": "assets/kanban.json", "mesh": "assets/mesh.json"}}
    (target_dir / "team.yaml").write_text(_dump_yaml(team))
    (target_dir / "crons.yaml").write_text(_dump_yaml({"crons": []}))
    souls = target_dir / "souls"
    souls.mkdir(parents=True, exist_ok=True)
    for i, role in enumerate(roles, start=1):
        rdict = role_dicts[i - 1]
        (souls / f"{role}.md").write_text(
            _DEFAULT_ROLE_TEMPLATE.format(role=role, team=team_name, rid=f"R{i}",
                                          summary=f"You are a member of the '{team_name}' team.",
                                          edges=_edge_lines(edges, role)))
    _write_assets(target_dir, team_name, role_dicts, edges)


def _dump_yaml(data: dict) -> str:
    try:
        import yaml
        return yaml.safe_dump(data, sort_keys=False, allow_unicode=True)
    except ImportError:  # pragma: no cover
        return json.dumps(data, indent=2)


def _owner_blueprint_root(home: Path | None = None) -> Path:
    """Owner-configurable blueprint root: <target home>/config/teamops.yaml
    key factory.blueprints_root, else the plugin's blueprints dir."""
    try:
        from .tools import default_home
        cfg_home = home if home is not None else default_home()
        cfg = Path(cfg_home) / "config" / "teamops.yaml"
        if cfg.exists():
            import yaml
            doc = yaml.safe_load(cfg.read_text()) or {}
            factory_cfg = doc.get("factory") or {}
            root = factory_cfg.get("blueprints_root")
            if root:
                return Path(root).expanduser()
    except Exception:  # noqa: BLE001
        pass
    return BLUEPRINTS_DIR


def generate_blueprint(spec: str, name: str | None = None, base: str | None = None,
                       use_fixture: bool = False, home: Path | None = None) -> tuple[Path, dict]:
    """Generate a blueprint for a spec using the in-plugin template engine.

    Returns (blueprint_root, meta) with meta['source'] in
    {"fixture", "extend", "scaffold"}. Writes ONLY under the owner-configurable
    blueprint root (default: the plugin's ``blueprints/`` dir).
    """
    slug = _slugify(name or spec)
    root = _owner_blueprint_root(Path(home) if home else None)
    target = root / slug

    # Fixture path (demos/tests): deterministic pre-baked output.
    if use_fixture:
        fixture = FIXTURES_DIR / slug
        if fixture.exists() and (fixture / "team.yaml").exists():
            return fixture, {"source": "fixture", "spec": spec,
                             "note": "pre-baked fixture requested"}
        # any fixture as fallback
        if FIXTURES_DIR.is_dir():
            for d in sorted(FIXTURES_DIR.iterdir()):
                if d.is_dir() and (d / "team.yaml").exists():
                    return d, {"source": "fixture", "spec": spec,
                               "note": f"nearest fixture {d.name}"}
        raise FileNotFoundError(f"no pre-baked fixture for {slug}")

    role, base_name = _parse_spec(spec)
    extension_base = base or base_name
    if extension_base:
        base_dir = ((root / extension_base) if (root / extension_base).exists()
                    else BLUEPRINTS_DIR / extension_base)
        if not (base_dir / "team.yaml").exists():
            raise FileNotFoundError(
                f"base blueprint '{extension_base}' not found under {root} (or the plugin blueprints dir)")
        role = role or "new-agent"
        try:
            import yaml
            base_roles = yaml.safe_load((base_dir / "team.yaml").read_text()) or {}
            existing = {r.get("name") for r in (base_roles.get("roles") or [])}
        except Exception:  # noqa: BLE001 — fall through; _extend_blueprint re-checks
            existing = set()
        if role in existing:
            raise ValueError(f"role '{role}' already exists in base blueprint {extension_base}")
        if target.exists():
            shutil.rmtree(target)
        target.mkdir(parents=True, exist_ok=True)
        try:
            _extend_blueprint(base_dir, role, slug, spec, target)
        except Exception:
            if target.exists():
                shutil.rmtree(target)
            raise
        return target, {"source": "extend", "spec": spec, "note": f"extended '{base_dir.name}' with role '{role}'",
                        "summary": f"Added {role} to {base_dir.name}."}

    # Scaffold a new minimal team from the roles named in the spec.
    if target.exists():
        shutil.rmtree(target)
    target.mkdir(parents=True, exist_ok=True)
    fallback = slug
    roles = _roles_from_spec(spec, fallback)
    _scaffold_team(spec, slug, roles[:12], target)
    return target, {"source": "scaffold", "spec": spec,
                    "note": f"scaffolded team '{slug}' with roles {roles}",
                    "summary": f"Scaffolded {len(roles)}-role team."}


def bake_fixture_from(name: str, target_name: str | None = None) -> Path:
    """Copy an existing blueprint into fixtures/ (used to pre-bake the demo fixture)."""
    src = BLUEPRINTS_DIR / name
    dst = FIXTURES_DIR / (target_name or name)
    if not (src / "team.yaml").exists():
        raise FileNotFoundError(f"no blueprint {name}")
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst)
    return dst
